export type WeightageTier = 'tier-1-high' | 'tier-2-medium' | 'tier-3-standard';

export interface SubtopicNode {
  id: string;                      // Globally unique subtopic identifier (e.g. "cse-em-dm-prop-logic")
  label: string;                   // Display title (e.g. "Propositional Logic")
  subtopicSlug: string;            // Canonical subtopic slug matching GateQA question bank
  tags: string[];                  // Related tags for matching questions
  keyConcepts?: string[];          // Syllabus bullet points
}

export interface TopicNode {
  id: string;                      // Globally unique topic identifier (e.g. "cse-em-discrete-math")
  label: string;                   // Display title (e.g. "Discrete Mathematics")
  subjectSlug: string;             // Primary subject slug (e.g. "discrete-math")
  canonicalSubjectSlugs?: string[];// Specific question bank subject slugs (e.g. ["discrete-math"])
  primaryTopicTag: string;         // Canonical tag for 1:1 quantitative PYQ attribution
  secondaryTopicTags: string[];    // Related tags for rich practice filtering
  estimatedHours: number;          // Estimated preparation hours
  weightageTier: WeightageTier;    // Weightage priority tier
  marksRange: string;              // Typical marks range in GATE
  keyConcepts: string[];           // Core syllabus bullet points
  recommendedTextbook?: string;    // Standard reference book
  subtopics?: SubtopicNode[];      // Nested subtopics
}

export interface SubjectNode {
  id: string;                      // e.g. "cse-os"
  slug: string;                    // e.g. "os"
  canonicalSubjectSlugs: string[]; // Slugs used in GateQA question bank
  track: 'cse' | 'da';
  label: string;                   // e.g. "Operating Systems"
  shortLabel: string;              // e.g. "OS"
  marksRange: string;              // e.g. "7–10 Marks"
  estimatedHours: number;          // e.g. 35
  weightageTier: WeightageTier;
  recommendedTextbook: string;
  topics: TopicNode[];
}

export interface TrackTaxonomy {
  track: 'cse' | 'da';
  title: string;
  defaultExamDate: string;
  subjects: SubjectNode[];
}

